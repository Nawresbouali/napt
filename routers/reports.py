SEV_COLOR = {
    "critical": (255,68,102), "high": (255,170,0),
    "medium":   (255,204,0),  "low":  (0,200,120),
}

class RapportPDF(FPDF):
    def __init__(self, t):
        super().__init__()
        self.t = t
    def header(self):
        self.set_font("Helvetica", "B", 15)
        self.set_text_color(30, 144, 255)
        self.cell(0, 12, "N.A.P.T - Nawres Autonomous Pentest Tool", align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_font("Helvetica", "", 10)
        self.set_text_color(120, 120, 120)
        self.cell(0, 7, self.t["sous_titre"], align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(30, 144, 255)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(4)
    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, f"Page {self.page_no()} | {self.t['footer']} | {datetime.now().strftime('%d/%m/%Y')}", align="C")
    def section(self, titre):
        self.ln(4)
        self.set_font("Helvetica", "B", 12)
        self.set_fill_color(30, 144, 255)
        self.set_text_color(255, 255, 255)
        self.cell(0, 9, f"  {titre}", fill=True, new_x="LMARGIN", new_y="NEXT")
        self.ln(2)
        self.set_text_color(0, 0, 0)

def generer_pdf(scans, lang="fr"):
    t = LANGUES.get(lang, LANGUES["fr"])
    pdf = RapportPDF(t)
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()

    # Resume
    pdf.section(t["resume"])
    pdf.set_font("Helvetica", "", 10)
    total = len(scans)
    by_sev = {}
    for s in scans:
        k = (s.severity or "unknown").lower()
        by_sev[k] = by_sev.get(k, 0) + 1
    pdf.cell(0, 7, f"{t['total']} : {total}", new_x="LMARGIN", new_y="NEXT")
    for sev, count in by_sev.items():
        pdf.cell(0, 6, f"  - {sev} : {count}", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)
    pdf.cell(0, 7, f"{t['genere']} - {datetime.now().strftime('%d/%m/%Y %H:%M')}", new_x="LMARGIN", new_y="NEXT")

    # Detail
    pdf.section(t["detail"])
    if not scans:
        pdf.set_font("Helvetica", "I", 10)
        pdf.cell(0, 8, t["aucun"], new_x="LMARGIN", new_y="NEXT")
    else:
        cols = [(t["col_cible"],55),(t["col_type"],22),(t["col_cve"],38),(t["col_sev"],25),(t["col_cvss"],18),(t["col_statut"],22)]
        pdf.set_font("Helvetica", "B", 8)
        pdf.set_fill_color(230, 230, 230)
        for label, w in cols:
            pdf.cell(w, 7, label, border=1, fill=True, align="C")
        pdf.ln()
        pdf.set_font("Helvetica", "", 7)
        fill = False
        for s in scans:
            sev = (s.severity or "").lower()
            r,g,b = SEV_COLOR.get(sev, (180,180,180))
            pdf.set_fill_color(248,248,248) if fill else pdf.set_fill_color(255,255,255)
            pdf.cell(55, 6, str(s.target or "")[:28], border=1, fill=fill)
            pdf.cell(22, 6, str(s.target_type or "")[:10], border=1, fill=fill)
            pdf.cell(38, 6, str(s.cve_id or "-")[:20], border=1, fill=fill)
            pdf.set_text_color(r,g,b)
            pdf.set_font("Helvetica", "B", 7)
            pdf.cell(25, 6, str(s.severity or "-")[:10], border=1, fill=fill, align="C")
            pdf.set_text_color(0,0,0)
            pdf.set_font("Helvetica", "", 7)
            pdf.cell(18, 6, str(s.cvss_score or "-")[:6], border=1, fill=fill, align="C")
            pdf.cell(22, 6, str(s.status or "-")[:10], border=1, fill=fill, align="C")
            pdf.ln()
            fill = not fill

    # Recommandations
    pdf.section(t["reco"])
    pdf.set_font("Helvetica", "", 9)
    for s in scans:
        if s.client_summary:
            pdf.set_font("Helvetica", "B", 9)
            pdf.cell(0, 6, f"[{str(s.target or '?')[:50]}]", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 9)
            pdf.multi_cell(0, 5, str(s.client_summary)[:400])
            pdf.ln(1)

    buf = BytesIO()
    pdf.output(buf)
    return buf.getvalue()

@router.get("/langues")
def liste_langues(_: User = Depends(get_current_user)):
    return [
        {"code": "fr", "nom": "Francais", "drapeau": "FR"},
        {"code": "en", "nom": "English",  "drapeau": "EN"},
    ]

@router.get("/generer")
def generer_rapport(
    lang: str = Query(default="fr"),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    scans = db.query(Scan).all()
    pdf_bytes = generer_pdf(scans, lang)
    filename = f"NAPT_Rapport_{lang.upper()}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
    return StreamingResponse(
        BytesIO(pdf_bytes),
        media_type="application/pdf",
        headers={"Content-Disposition": f"attachment; filename={filename}"}
    )
